def _fixtures(s: Session) -> dict[str, bytes]:
    """evals/checks/<unit>/must-pass|must-fail/<file> from the session's `example_good` and `example_bad`."""
    out: dict[str, bytes] = {}
    producer = {k: u.name for u in s.blueprint.units for k in u.produces}
    checked = [u.name for u in s.blueprint.units if u.check]
    for src in s.authoring.get("sources") or []:
        if not isinstance(src, dict) or src.get("kind") not in ("example_good", "example_bad"):
            continue
        loc = str(src.get("locator") or "")
        if not loc.startswith("saved:"):
            continue
        path = s.folder / "sources" / loc[len("saved:"):]
        if not path.is_file():
            continue
        key = str(src.get("artifact") or path.stem)
        unit = str(src.get("unit") or producer.get(key) or (checked[-1] if checked else ""))
        if not unit:
            continue
        which = "must-pass" if src["kind"] == "example_good" else "must-fail"
        name = f"{key}{path.suffix}"
        out[f"evals/checks/{unit}/{which}/{name}"] = path.read_bytes()
    for rel, data in list(out.items()):
        unit, which, name = rel.split("/")[2:5]
        bad = f"evals/checks/{unit}/must-fail/{name}"
        if which == "must-pass" and not any(k.startswith(f"evals/checks/{unit}/must-fail/") for k in out):
            out[bad] = _remove_checked(data)
    return out


def _remove_checked(good: bytes) -> bytes:
    """A must-fail fixture from a good one: every heading after the first removed, else an empty file."""
    lines = good.decode("utf-8", "replace").splitlines(keepends=True)
    heads = [i for i, ln in enumerate(lines) if ln.lstrip().startswith("#")]
    if len(heads) < 2:
        return b""
    keep = [ln for i, ln in enumerate(lines) if i not in heads[1:]]
    return "".join(keep).encode("utf-8")


def files(s: Session) -> dict[str, bytes]:
    bp, o = s.blueprint, s.outcome
    mod = _module(bp.name)
    init, checks_src, _todo = _declaration(s, mod)
    routing = _routing_file(s)
    author = s.authoring.get("author") or "Workflow author"
    out: dict[str, bytes] = {}

    def put(rel: str, text: str) -> None:
        out[rel] = text.encode("utf-8")

    def put_json(rel: str, doc: Any) -> None:
        put(rel, json.dumps(doc, indent=2, ensure_ascii=False) + "\n")

    put_json(".claude-plugin/plugin.json", {"name": bp.name, "version": "0.1.0",
                                            "description": _first_sentence(str(o.get("statement", ""))),
                                            "author": {"name": str(author)}, "dependencies": ["tempergraph"]})
    put_json("tempergraph.json", {"schema_version": 1, "name": bp.name, "entry": f"{mod}:workflow",
                                  "workflow_api": WORKFLOW_API, "docs": "provisional"})
    authored = dict(o)
    authored["revision"] = int(o.get("revision") or 1)
    if not authored.get("revisions"):
        authored["revisions"] = [{"revision": authored["revision"], "origin": "authored", "at": now_iso()}]
    put_json("outcome.json", authored)
    put_json("blueprint.json", s.blueprint_doc)
    put("workflow/pyproject.toml", f'[project]\nname = "tgwf-{bp.name}"\nrequires-python = ">=3.11"\n'
        "dependencies = []\n")
    put(f"workflow/{mod}/__init__.py", init)
    if checks_src:
        put(f"workflow/{mod}/checks.py", checks_src)
    if routing:
        put(f"workflow/{mod}/routing.py", routing)
    for u in bp.units:
        if u.kind == "step":
            put(f"prompts/{u.name}.md", _prompt(u, _unit_criteria(o, u.name)))
        if u.judge:
            put(f"judges/{u.name}.md", _judge(u))
    put_json("evals/cases.json", {"schema_version": 1, "cases": s.cases})
    out.update(_fixtures(s))
    put("README.md", f"# {bp.name}\n\n{o.get('statement', '')}\n\nStart: `tempergraph run {bp.name} <request>`.\n")
    put("docs/README.md", "# Docs\n\nRules: provisional (the engine's docs README). Criterion text lives in "
        "`outcome.json`; the specs name each criterion by id.\n")
    put("docs/specs/00-overview.spec.md", _overview(s))
    for i, u in enumerate(bp.units):
        put(f"docs/specs/{i + 1:02d}-{u.name}.spec.md", _unit_spec(u, s))
    for i, d in enumerate(d for d in s.authoring.get("decisions") or [] if isinstance(d, dict)):
        put(f"docs/adr/{i + 1:04d}-{re.sub(r'[^a-z0-9]+', '-', str(d.get('subject', 'decision')).lower()).strip('-')}"
            ".adr.md", _adr(i + 1, d))
    put("docs/research/sources.rsrch.md", _sources(s))
    put(f"tests/test_{mod}_generated.py", GENERATED_TEST.format(generated=GENERATED))
    return out


def _routing_file(s: Session) -> str:
    fns = []
    for u in s.blueprint.units:
        fn = u.name.replace("-", "_")
        shape = dict(s.blueprint.flow.get(u.name) or {})
        if u.kind == "route" or (u.kind == "step" and shape.get("route")):
            targets = list(shape.get("route") or ())
            fns.append(f"def route_{fn}(view):\n    \"\"\"Pick one of {targets}; replace this default.\"\"\"\n"
                       f"    return {targets[0] if targets else 'finalizer'!r}\n")
        elif u.kind == "switch":
            sw = shape.get("switch") or {}
            fns.append(f"def switch_{fn}(view):\n    \"\"\"Return an arm name; replace this default.\"\"\"\n"
                       f"    return {str(sw.get('default') or '')!r}\n")
        elif u.kind == "script":
            fns.append(f"def script_{fn}(ctx):\n    \"\"\"The {u.name} script; write it before verify.\"\"\"\n"
                       "    raise NotImplementedError\n")
    if not fns:
        return ""
    return f'"""{GENERATED} Defaults to replace before `author verify`."""\n\n\n' + "\n\n".join(fns)


AC_SECTION = re.compile(r"(^## 6\. Acceptance criteria\n\n)(.*?)(?=^## |\Z)", re.M | re.S)


def _merge_acceptance(current: str, generated: str) -> str:
    """Keep the person's prose; replace only the acceptance criteria section with the generated one."""
    new = AC_SECTION.search(generated)
    if new is None or AC_SECTION.search(current) is None:
        return current
    return AC_SECTION.sub(lambda m: m.group(1) + new.group(2), current, count=1)


def scaffold(session: Session, out: Path, *, update: bool = False, docs_only: bool = False) -> ScaffoldReport:
    out = out.resolve()
    record_path = out / "authoring.json"
    previous: dict[str, str] = {}
    if out.exists() and any(out.iterdir()):
        if not update:
            raise ScaffoldRefused("out-not-empty", f"{out} exists and is not empty; use --update for this workflow")
        try:
            prior = _json(record_path)
            previous = dict((prior.get("scaffold") or {}).get("files") or {})
        except (OSError, ValueError):
            prior = {}
        try:
            name = _json(out / "tempergraph.json").get("name")
        except (OSError, ValueError):
            name = None
        if name != session.blueprint.name:
            raise ScaffoldRefused("out-not-this-workflow", f"{out} holds {name!r}, not {session.blueprint.name!r}")
    elif update:
        raise ScaffoldRefused("nothing-to-update", f"{out} has no package to update")
    rep = ScaffoldReport(out=out)
    _, _, todo = _declaration(session, _module(session.blueprint.name))
    rep.to_write = todo
    recorded: dict[str, str] = {}
    for rel, data in sorted(files(session).items()):
        if docs_only and not rel.startswith("docs/") and rel != "outcome.json":
            if rel in previous:
                recorded[rel] = previous[rel]
            continue
        path = out / rel
        new_digest = _sha(data)
        if path.exists():
            have = _sha(path.read_bytes())
            if have == new_digest:
                rep.unchanged.append(rel)
                recorded[rel] = new_digest
                continue
            if rel != "outcome.json" and previous.get(rel) != have:
                rep.person_edited.append(rel)  # SCF-B7: never overwritten
                if rel.startswith("docs/specs/"):
                    merged = _merge_acceptance(path.read_text(encoding="utf-8"), data.decode("utf-8"))
                    if merged != path.read_text(encoding="utf-8"):
                        path.write_text(merged, encoding="utf-8")
                if rel in previous:
                    recorded[rel] = previous[rel]
                continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        rep.written.append(rel)
        recorded[rel] = new_digest
    record = dict(session.authoring)
    record["scaffold"] = {"files": recorded, "at": now_iso()}
    write_json(record_path, record, mode=0o644)
    if not docs_only:
        _diagram(out, rep)
    return rep


def _diagram(out: Path, rep: ScaffoldReport) -> None:
    """`diagram/` is generated from the built spec, never from the blueprint (SCF §2.4)."""
    from tempergraph.model.diagram import diagram_model, to_mermaid
    from tempergraph.package.loader import PackageNotLoaded, load_package

    try:
        spec = load_package(out).spec
    except PackageNotLoaded as exc:
        rep.to_write.append(f"diagram: the package does not load yet ({exc})")
        return
    model = diagram_model(spec)
    write_json(out / "diagram" / "model.json", model, mode=0o644)
    (out / "diagram" / "workflow.md").write_text("```mermaid\n" + to_mermaid(model) + "\n```\n", encoding="utf-8")
    rep.written += ["diagram/model.json", "diagram/workflow.md"]
