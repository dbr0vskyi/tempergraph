"""`scaffold <session> --out <dir> [--update] [--update-docs]` (SCF §2.4): write a workflow package from an
approved authoring session. Model-free.

The session folder (AUT §2.1, release 1 layout, SCF §2.7) holds `authoring.json`, `blueprint.json`,
`outcome.json`, optional `cases.json` and `sources/` with the saved example files. Phase 7 is approved
when `authoring.json` `phases[]` has an entry `{phase: 7, approved_at}` and `blueprint_digest` and
`outcome_revision` match the drafts.

Every file written is recorded with its digest in the package's `authoring.json` `scaffold.files`;
`--update` rewrites a file only when it still has the digest it was written with, and lists the others as
person-edited. A person-edited unit spec keeps its prose; only its acceptance criteria section is
regenerated from `outcome.json`.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from tempergraph.author.blueprint import Blueprint, digest, parse
from tempergraph.constants import WORKFLOW_API
from tempergraph.docs import write_json
from tempergraph.store.layout import now_iso

GENERATED = "Generated by `tempergraph scaffold` (SCF §2.4)."


class ScaffoldRefused(Exception):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(f"{code}: {message}")
        self.code = code


@dataclass(kw_only=True)
class ScaffoldReport:
    out: Path
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    person_edited: list[str] = field(default_factory=list)
    to_write: list[str] = field(default_factory=list)  # stubs the person writes before verify

    def to_json(self) -> dict[str, Any]:
        return {"schema_version": 1, "out": str(self.out), "written": self.written, "unchanged": self.unchanged,
                "person_edited": self.person_edited, "to_write": self.to_write}


@dataclass(frozen=True, kw_only=True)
class Session:
    folder: Path
    authoring: dict[str, Any]
    blueprint: Blueprint
    blueprint_doc: dict[str, Any]
    outcome: dict[str, Any]
    cases: list[dict[str, Any]]


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def read_session(folder: Path) -> Session:
    try:
        authoring = _json(folder / "authoring.json")
        bp_doc = _json(folder / "blueprint.json")
        outcome = _json(folder / "outcome.json")
    except (OSError, ValueError) as exc:
        raise ScaffoldRefused("session-unreadable", f"{folder}: {type(exc).__name__}") from exc
    bp = parse(bp_doc)
    if isinstance(bp, list):
        raise ScaffoldRefused("blueprint-invalid", "; ".join(f.message for f in bp))
    approved = any(isinstance(p, dict) and p.get("phase") == 7 and p.get("approved_at")
                   for p in authoring.get("phases") or [])
    if not approved:
        raise ScaffoldRefused("blueprint_not_approved", "phase 7 (the blueprint, outcome and verification tables) "
                              "is not approved (AUT §2.2)")
    if authoring.get("blueprint_digest") != digest(bp_doc) or authoring.get("outcome_revision") != outcome.get(
            "revision"):
        raise ScaffoldRefused("blueprint_not_approved", "the blueprint or the outcome changed after approval; "
                              "draw and approve again")
    cases: list[dict[str, Any]] = []
    if (folder / "cases.json").is_file():
        cases = [c for c in (_json(folder / "cases.json").get("cases") or []) if isinstance(c, dict)]
    return Session(folder=folder, authoring=authoring, blueprint=bp, blueprint_doc=bp_doc, outcome=outcome, cases=cases)


# -- the files ------------------------------------------------------------------------------------------------------


def _module(name: str) -> str:
    return name.replace("-", "_")


def _first_sentence(text: str) -> str:
    m = re.match(r"(.+?[.!?])(\s|$)", text.strip())
    return (m.group(1) if m else text.strip())[:200]


def _kinds(outcome: dict[str, Any]) -> dict[str, str]:
    return {str(d.get("key")): str(d.get("kind") or "file") for d in outcome.get("deliverables") or []
            if isinstance(d, dict) and d.get("key")}


def _unit_criteria(outcome: dict[str, Any], unit: str) -> list[dict[str, Any]]:
    io = (outcome.get("intermediate") or {}).get(unit) or {}
    return [c for c in io.get("criteria") or [] if isinstance(c, dict)]


def _check_body(unit: str, crits: list[dict[str, Any]]) -> tuple[str, list[str], list[str]]:
    """(the check function source, allow-listed command prefixes, criteria the person must write)."""
    lines = [f"def {unit.replace('-', '_')}_check(ctx):", f'    """The {unit} gate\'s check (OUT §2.2)."""',
             "    found = []"]
    commands: list[str] = []
    todo: list[str] = []
    for c in crits:
        if c.get("verified_by") != "check":
            continue
        cid = str(c.get("id"))
        v = c.get("verifier") or {}
        prim = v.get("primitive")
        if prim in ("file_present", "git_clean", "git_pushed"):
            args = [] if prim.startswith("git") else [repr(str(v.get("artifact", "")))]
            lines.append(f"    found.append(checks.{prim}(ctx, {', '.join([*args, repr(cid)])}))")
        elif prim == "headings_in_order":
            lines.append(f"    found.append(checks.headings_in_order(ctx, {str(v.get('artifact', ''))!r}, "
                         f"{list(v.get('headings') or [])!r}, {cid!r}))")
        elif prim in ("pattern_present", "pattern_absent"):
            lines.append(f"    found.append(checks.{prim}(ctx, {str(v.get('artifact', ''))!r}, "
                         f"{str(v.get('pattern', ''))!r}, {cid!r}))")
        elif prim == "value_in_choices":
            lines.append(f"    found.append(checks.value_in_choices(ctx, {str(v.get('artifact', ''))!r}, "
                         f"{list(v.get('choices') or [])!r}, {cid!r}))")
        elif v.get("command"):
            cmd = str(v["command"])
            commands.append(cmd)
            lines += [f"    run = ctx.run({cmd!r})",
                      f"    found.append(CheckFinding(status='pass' if run.exit_code == 0 else 'fail', "
                      f"criterion={cid!r}, place={cmd!r}, message='' if run.exit_code == 0 else 'the command failed'))"]
        else:
            todo.append(cid)
            lines.append(f"    # TODO({cid}): write this check; until then it never passes")
            lines.append(f"    found.append(CheckFinding(status='maybe', criterion={cid!r}, "
                         f"message='the check for {cid} is not written yet'))")
    lines.append("    return checks.result(found)")
    return "\n".join(lines) + "\n", commands, todo


def _declaration(s: Session, mod: str) -> tuple[str, str, list[str]]:
    """(`__init__.py`, `checks.py`, criteria to write)."""
    bp, outcome = s.blueprint, s.outcome
    kinds = _kinds(outcome)
    imports = {"Gate", "Judge", "Routing", "Workflow"}
    check_fns: list[str] = []
    allow: list[str] = []
    todo: list[str] = []
    routing_fns: list[str] = []
    units = []
    for u in bp.units:
        crits = _unit_criteria(outcome, u.name)
        fn = u.name.replace("-", "_")
        gate = []
        if u.check:
            body, cmds, missing = _check_body(u.name, crits)
            check_fns.append(body)
            allow += [c for c in cmds if c not in allow]
            todo += missing
            gate.append(f"check={fn}_check")
        if u.judge:
            refs = sorted(set(u.produces) | set(u.reads))
            gate.append(f'judge=Judge(file="judges/{u.name}.md", references={refs!r})')
        if u.approval or u.signoff:
            gate.append("approval=True")
        if u.on_fail:
            gate.append(f"on_fail={u.on_fail!r}")
        if u.on_budget_spent:
            gate.append(f"on_budget_spent={u.on_budget_spent!r}")
        if u.back_targets:
            gate.append(f"back_targets={list(u.back_targets)!r}")
        gate_src = f"Gate({', '.join(gate)})"
        shape = dict(bp.flow.get(u.name) or {})
        produces = {k: kinds.get(k, "file") for k in u.produces}
        if u.kind == "route":
            imports.add("Route")
            targets = list(shape.get("route") or ())
            routing_fns.append(f"def route_{fn}(view):\n    \"\"\"Pick one of {targets}; replace this default.\"\"\"\n"
                               f"    return {targets[0] if targets else 'finalizer'!r}\n")
            units.append(f'"{u.name}": Route(select=route_{fn}, targets={targets!r}, gate={gate_src})')
            todo.append(f"route_{fn}")
        elif u.kind == "switch":
            imports.add("Switch")
            sw = shape.get("switch") or {}
            routing_fns.append(f"def switch_{fn}(view):\n    \"\"\"Return an arm name; replace this default.\"\"\"\n"
                               f"    return {str(sw.get('default') or '')!r}\n")
            units.append(f'"{u.name}": Switch(predicate=switch_{fn}, arms={dict(sw.get("arms") or {})!r}, '
                         f'default={str(sw.get("default") or "")!r}, gate={gate_src})')
            todo.append(f"switch_{fn}")
        elif u.kind == "script":
            imports.add("Script")
            routing_fns.append(f"def script_{fn}(ctx):\n    \"\"\"The {u.name} script; write it before verify.\"\"\"\n"
                               "    raise NotImplementedError\n")
            units.append(f'"{u.name}": Script(call=script_{fn}, produces={produces!r}, inputs={list(u.reads)!r}, '
                         f'summary={u.summary!r}, gate={gate_src})')
            todo.append(f"script_{fn}")
        else:
            imports |= {"Step", "text"}
            extra = ""
            route = list(shape.get("route") or ())
            if route:
                routing_fns.append(f"def route_{fn}(view):\n    \"\"\"Pick one of {route}; replace this default.\"\"\"\n"
                                   f"    return {route[0]!r}\n")
                extra = f", route=route_{fn}, route_targets={route!r}"
                todo.append(f"route_{fn}")
            executor = f", executor={u.executor!r}" if u.executor else ""
            units.append(f'"{u.name}": Step(prompt=text("prompts/{u.name}.md"), summary={u.summary!r}, '
                         f'tools=["read", "write"], produces={produces!r}{executor}{extra}, gate={gate_src})')
    a = s.authoring
    routing = a.get("routing") or {}
    description = str(routing.get("description") or _first_sentence(str(outcome.get("statement", ""))))
    fields = [f"order={[u.name for u in bp.units]!r}",
              f"routing=Routing(description={description!r}"
              + (f", when_to_use={str(routing['when_to_use'])!r}" if routing.get("when_to_use") else "") + ")",
              f"issue_repository={str(a.get('issue_repository') or '')!r}"]
    if allow:
        fields.append(f"allow_commands={allow!r}")
    body = ",\n        ".join(units)
    init = [f'"""{GENERATED} The workflow\'s declaration (PKG §2.4)."""', "",
            f"from tempergraph.api import {', '.join(sorted(imports))}", ""]
    if check_fns:
        init.append("from .checks import " + ", ".join(f"{u.name.replace('-', '_')}_check" for u in bp.units
                                                       if u.check))
    if routing_fns:
        names = [ln.split("(")[0][4:] for fn_src in routing_fns for ln in fn_src.splitlines()[:1]]
        init.append("from .routing import " + ", ".join(names))
    init += ["", "", "def workflow():", "    return Workflow(", "        " + ",\n        ".join(fields) + ",",
             "        units={", f"        {body},", "        },", "    )", ""]
    checks_src = "\n".join([f'"""{GENERATED} Review each check before `author verify`."""', "",
                            "from tempergraph.api import CheckFinding, checks", "", "", "\n\n".join(check_fns)])
    return "\n".join(init), checks_src if check_fns else "", todo


def _prompt(u: Any, crits: list[dict[str, Any]]) -> str:
    lines = [f"# {u.name}", "", u.summary or "", "", "The request: {request}"]
    lines += [f"Read `{r}`: {{{r}}}" for r in u.reads]
    judged = [c for c in crits if c.get("verified_by") in ("judge", "check", "person")]
    if judged:
        lines += ["", "## What a good result shows", ""]
        for c in judged:
            met = ((c.get("verifier") or {}).get("scale") or {}).get("met")
            lines.append(f"- {c.get('text')}" + (f" ({met})" if met else ""))
    if u.produces:
        lines += ["", "## Output", ""] + [f"- Write `{k}` and name its path." for k in u.produces]
    return "\n".join(lines) + "\n"


def _judge(u: Any) -> str:
    refs = ", ".join(f"`{k}`" for k in sorted(set(u.produces) | set(u.reads))) or "the step's output"
    return (f"# Stance\n\nThe artifacts are the truth; what the step said about them is a claim to verify.\n\n"
            f"# Brief\n\nRead {refs}. Grade each criterion by its check method and scale, citing the evidence it "
            "asks for.\n")


def _ac(rows: list[dict[str, Any]]) -> str:
    return "\n".join(f"- [ ] {c.get('id')} {' '.join(str(c.get('text', '')).split())}" for c in rows if c.get("id")) or "none"


def _overview(s: Session) -> str:
    o, bp = s.outcome, s.blueprint
    units = "\n".join(f"- [{u.name}]({i + 1:02d}-{u.name}.spec.md): {u.summary}" for i, u in enumerate(bp.units))
    assumptions = "\n".join(f"- {a}" for a in o.get("assumptions") or []) or "none"
    return (f"# {bp.name}\n\n## 1. Overview\n\n{o.get('statement', '')}\n\nUnits:\n\n{units}\n\n"
            f"## 6. Acceptance criteria\n\n{_ac(o.get('final') or [])}\n\n## Open questions\n\n{assumptions}\n")


def _unit_spec(u: Any, s: Session) -> str:
    io = (s.outcome.get("intermediate") or {}).get(u.name) or {}
    return (f"# {u.name}\n\n## 1. Overview\n\n{io.get('statement') or u.summary}\n\nPart of the "
            f"[overview](00-overview.spec.md).\n\n## 6. Acceptance criteria\n\n{_ac(_unit_criteria(s.outcome, u.name))}\n")


def _adr(n: int, d: dict[str, Any]) -> str:
    return (f"# {n:04d} {d.get('subject', 'decision')}\n\nStatus: accepted\n\n## Decision\n\n{d.get('choice', '')}\n\n"
            f"## Alternatives\n\n{', '.join(map(str, d.get('alternatives') or [])) or 'none recorded'}\n\n"
            f"## Consequence\n\n{d.get('consequence', '') or 'not recorded'}\n")


def _sources(s: Session) -> str:
    rows = [f"| {x.get('id', '')} | {x.get('kind', '')} | {x.get('digest', '')[:12]} |"
            for x in s.authoring.get("sources") or [] if isinstance(x, dict)]
    return ("# Sources\n\nWhat the authoring session read (metadata only; the text stays in the session).\n\n"
            "| Id | Kind | Digest |\n|---|---|---|\n" + ("\n".join(rows) or "| none | | |") + "\n")


